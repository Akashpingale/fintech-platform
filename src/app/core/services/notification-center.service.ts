import { Injectable, computed, inject } from '@angular/core';
import { Observable, forkJoin, map, of } from 'rxjs';
import { AppNotification } from '../models/notification.model';
import { CollectionStore } from './collection.store';
import { AuthService } from './auth.service';
import { BudgetService } from './budget.service';
import { GoalService } from './goal.service';
import { SipService } from './sip.service';
import { WatchlistService } from './watchlist.service';

/** Icon and colour for each notification type. */
export const NOTIFICATION_META: Record<
  AppNotification['type'],
  { icon: string; tone: 'danger' | 'success' | 'warning' | 'primary'; label: string }
> = {
  budget: { icon: 'account_balance_wallet', tone: 'danger', label: 'Budget' },
  goal: { icon: 'flag', tone: 'success', label: 'Goal' },
  sip: { icon: 'autorenew', tone: 'primary', label: 'SIP' },
  price: { icon: 'trending_up', tone: 'warning', label: 'Price alert' },
};

/**
 * The in-app notification centre.
 *
 * Alerts are generated by inspecting the other stores (budgets at/over limit,
 * goals reached, SIPs due, watchlist alerts crossed). Each alert carries a
 * stable dedupe key inside its message so re-running generation does not
 * create duplicates.
 */
@Injectable({ providedIn: 'root' })
export class NotificationCenterService extends CollectionStore<AppNotification> {
  protected readonly endpoint = '/notifications';
  protected readonly storageKey = 'notifications';

  private readonly auth = inject(AuthService);
  private readonly budgets = inject(BudgetService);
  private readonly goals = inject(GoalService);
  private readonly sips = inject(SipService);
  private readonly watchlist = inject(WatchlistService);

  /** Newest first. */
  readonly sorted = computed(() =>
    [...this.items()].sort(
      (a, b) =>
        new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime()
    )
  );

  readonly unread = computed(() => this.sorted().filter(n => !n.read));
  readonly unreadCount = computed(() => this.unread().length);

  /** Marks one notification read. */
  markRead(id: string): Observable<AppNotification> {
    return this.patch(id, { read: true });
  }

  /** Marks every unread notification read. */
  markAllRead(): Observable<void> {
    const ids = this.unread().map(n => n.id);
    if (ids.length === 0) return of(undefined);
    return forkJoin(ids.map(id => this.patch(id, { read: true }))).pipe(
      map(() => undefined)
    );
  }

  /** Deletes every notification. */
  clearAll(): Observable<void> {
    return this.removeMany(this.items().map(n => n.id));
  }

  /** Raises one notification, ignoring it if the same message already exists. */
  push(
    type: AppNotification['type'],
    message: string
  ): Observable<AppNotification | null> {
    if (this.items().some(n => n.message === message)) return of(null);
    return this.create({
      userId: this.auth.userId(),
      type,
      message,
      read: false,
      createdAt: new Date().toISOString(),
    });
  }

  /**
   * Scans the other stores and raises any new alerts.
   * Returns the number of notifications created.
   */
  refreshAlerts(): Observable<number> {
    const messages: { type: AppNotification['type']; message: string }[] = [];

    // Budgets at 80% and 100% of their limit (Section 3.4).
    for (const progress of this.budgets.alerts()) {
      const { category } = progress.budget;
      if (progress.usage >= 100) {
        messages.push({
          type: 'budget',
          message: `${category} budget exceeded — you have spent ${Math.round(
            progress.usage
          )}% of the limit.`,
        });
      } else {
        messages.push({
          type: 'budget',
          message: `${category} budget at ${Math.round(
            progress.usage
          )}% — approaching the limit.`,
        });
      }
    }

    // Goals reached.
    for (const progress of this.goals.progress()) {
      if (progress.status === 'achieved') {
        messages.push({
          type: 'goal',
          message: `Goal reached: ${progress.goal.name} is fully funded.`,
        });
      }
    }

    // SIP instalments due within a week.
    for (const progress of this.sips.dueSoon()) {
      const due = progress.nextDueDate.toLocaleDateString('en-IN', {
        day: 'numeric',
        month: 'short',
      });
      messages.push({
        type: 'sip',
        message: `${progress.sip.fundName} SIP of ₹${progress.sip.amount.toLocaleString(
          'en-IN'
        )} is due on ${due}.`,
      });
    }

    // Watchlist price alerts crossed.
    for (const row of this.watchlist.triggeredRows()) {
      const threshold =
        row.triggered === 'above' ? row.item.alertAbove : row.item.alertBelow;
      messages.push({
        type: 'price',
        message: `${row.item.symbol} moved ${row.triggered} ₹${threshold?.toLocaleString(
          'en-IN'
        )} — now ₹${row.quote?.price.toLocaleString('en-IN')}.`,
      });
    }

    const existing = new Set(this.items().map(n => n.message));
    const fresh = messages.filter(m => !existing.has(m.message));
    if (fresh.length === 0) return of(0);

    return this.createMany(
      fresh.map(m => ({
        userId: this.auth.userId(),
        type: m.type,
        message: m.message,
        read: false,
        createdAt: new Date().toISOString(),
      }))
    ).pipe(map(created => created.length));
  }
}
